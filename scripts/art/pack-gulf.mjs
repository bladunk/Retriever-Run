import { createRequire } from 'node:module'
import { readFile, writeFile } from 'node:fs/promises'
import { resolve } from 'node:path'

const [scratch, tools, region = 'gulf'] = process.argv.slice(2)
if (!scratch || !tools || !['gulf', 'cypress'].includes(region))
  throw new Error('Usage: node scripts/art/pack-gulf.mjs <Blender output directory> <glTF tooling directory> [gulf|cypress]')
const require = createRequire(resolve(tools, 'package.json'))
const { NodeIO } = require('@gltf-transform/core')
const { EXTMeshoptCompression, KHRMeshQuantization } = require('@gltf-transform/extensions')
const { dedup, meshopt, prune, simplify, weld } = require('@gltf-transform/functions')
const { MeshoptEncoder, MeshoptSimplifier } = await import(require.resolve('meshoptimizer'))
await Promise.all([MeshoptEncoder.ready, MeshoptSimplifier.ready])
const io = new NodeIO().registerExtensions([EXTMeshoptCompression, KHRMeshQuantization])
  .registerDependencies({ 'meshopt.encoder': MeshoptEncoder })
const authorPath = resolve(scratch, `${region}-author.glb`)
const document = await io.read(authorPath)
await document.transform(weld(), simplify({ simplifier: MeshoptSimplifier, ratio: .68, error: .013 }), dedup(), prune({ keepAttributes: true }))

function base64(data) {
  return Buffer.from(data.buffer, data.byteOffset, data.byteLength).toString('base64')
}

const meshes = {}
const inventory = {}
for (const node of document.getRoot().listNodes()) {
  const mesh = node.getMesh()
  if (!mesh) continue
  if (mesh.listPrimitives().length !== 1) throw new Error('Author pack requires one indexed primitive per mesh')
  const primitive = mesh.listPrimitives()[0]
  const attribute = semantic => primitive.getAttribute(semantic).getArray()
  const color = attribute('COLOR_0')
  const pos = attribute('POSITION')
  const uv = attribute('TEXCOORD_0')
  const ids = primitive.getIndices().getArray()
  const count = pos.length / 3
  if (ids.length % 3 || ids.some(value => value >= count) || count > 65535)
    throw new Error('Invalid mesh topology ' + node.getName())
  if (!pos.every(Number.isFinite) || color.length !== count * 3 || uv.length !== count * 2)
    throw new Error('Invalid vertex attributes ' + node.getName())
  const linearColor = Uint8Array.from(color, value => Math.round(255 * Math.max(0, Math.min(1, value))))
  const name = node.getName()
  const layer = node.getExtras().trail_layer
  if (![0, 2, 5].includes(layer)) throw new Error('Unknown surface class ' + name)
  meshes[name] = {
    position: base64(Int16Array.from(pos, value => Math.round(value * 3072))),
    uv: base64(Int16Array.from(uv, value => Math.round(value * 4096))),
    normal: base64(Int16Array.from(attribute('NORMAL'), value => Math.round(value * 32767))),
    color: base64(linearColor), index: base64(Uint16Array.from(ids)), layer,
  }
  inventory[name] = { vertices: count, triangles: ids.length / 3 }
}
await writeFile(`src/assets/environment/${region}-meshes.js`,
  `// Generated by scripts/art/pack-gulf.mjs from art/blender/${region}.py.\nexport default ` + JSON.stringify(meshes, null, 2) + '\n')
await document.transform(meshopt({ encoder: MeshoptEncoder, level: 'medium' }))
const optimizedPath = resolve(scratch, `${region}-optimized.glb`)
await io.write(optimizedPath, document)
console.log(JSON.stringify({ inventory, glbAuthorBytes: (await readFile(authorPath)).length,
  glbOptimizedBytes: (await readFile(optimizedPath)).length }, null, 2))
